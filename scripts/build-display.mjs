// Fail closed: this tool builds only. Full-host output is never treated as flash-ready.
import {spawnSync} from "node:child_process";
import {existsSync,readFileSync} from "node:fs";
import {fileURLToPath} from "node:url";
import path from "node:path";
const root=fileURLToPath(new URL("..",import.meta.url));
const upstream=path.join(root,"upstream/stack-chan");
const fw=path.join(upstream,"firmware");
const req=JSON.parse(readFileSync(path.join(root,"port/target-requirements.json"),"utf8"));
const variant=process.argv[2]??"--face";
if(!["--face","--host"].includes(variant)||process.argv.length>3)throw Error("Use --face or --host");
if(!existsSync(path.join(fw,"package.json")))throw Error("Run git submodule update --init --recursive first");
const git=spawnSync("git",["rev-parse","HEAD"],{cwd:upstream,encoding:"utf8"});
if(git.status!==0||git.stdout.trim()!==req.upstream.commit)throw Error("Unexpected upstream revision");
if(!process.env.MODDABLE)throw Error("Set up Moddable SDK "+req.upstream.sdk+" first");
const sdk=readFileSync(path.join(process.env.MODDABLE,"tools/VERSION"),"utf8").trim();
if(sdk!==req.upstream.sdk)throw Error("SDK mismatch: "+sdk+"; expected "+req.upstream.sdk);
const target=variant==="--face"?"port/face-probe/manifest.json":"port/app/manifest.json";
if(variant==="--host")console.warn("EXPERIMENTAL BUILD ONLY: upstream audio/camera defaults are not yet hardware-safe. DO NOT FLASH.");
const result=spawnSync(process.execPath,["scripts/run-mcconfig.mjs","-m","-p","esp32:"+path.join(root,"port/sanny"),"-t","build",path.join(root,target)],{cwd:fw,stdio:"inherit"});
if(result.error)throw result.error;
process.exit(result.status??1);
